"""OAuth access/refresh token auth for the TextQL SDK.

Hand-written (not generated by Speakeasy). The generated ``api_key`` option can
only send the ``tql_api_key`` header, so token auth is injected under the SDK as
an ``httpx.Auth``: every request carries ``Authorization: Bearer <access_token>``,
the token is refreshed shortly before it expires, and a 401 triggers one refresh
and retry::

    from textql_sdk.oauth import OAuthTokens, from_tokens

    def save(tokens: OAuthTokens) -> None:
        ...  # persist tokens.refresh_token: the previous one is now spent

    sdk = from_tokens(
        access_token=...,
        refresh_token=...,
        client_id=...,
        client_secret=...,
        expires_in=3600,
        on_tokens=save,
    )

Refresh tokens are single use: the server rotates them on every refresh and
rejects a replayed one. Persist every pair handed to ``on_tokens``, and share
one :class:`TokenManager` between everything that refreshes the same grant.
"""

from __future__ import annotations

import asyncio
import base64
import hashlib
import secrets
import threading
import time
from dataclasses import dataclass
from typing import Any, Callable, Iterable, Optional
from urllib.parse import urlencode, urlparse

import httpx

from ._hooks.registration import server_url_from_env
from .sdk import Textql
from .sdkconfiguration import SERVERS

_REFRESH_MARGIN_SECONDS = 60


@dataclass(frozen=True)
class OAuthTokens:
    access_token: str
    refresh_token: Optional[str]
    expires_at: Optional[float]
    """Unix time the access token expires. ``None`` refreshes only on a 401."""


class OAuthRefreshError(Exception):
    """``/oauth/token`` refused a refresh or code exchange."""

    def __init__(
        self, status_code: int, error: str, description: Optional[str] = None
    ) -> None:
        self.status_code = status_code
        self.error = error
        self.description = description
        detail = f": {description}" if description else ""
        super().__init__(f"token refresh failed ({status_code} {error}){detail}")


def _origin(server_url: Optional[str]) -> str:
    url = urlparse(server_url or server_url_from_env() or SERVERS[0])
    return f"{url.scheme}://{url.netloc}"


def _token_url(server_url: Optional[str]) -> str:
    return f"{_origin(server_url)}/oauth/token"


def _post_token(
    token_url: str,
    data: dict,
    http_client: Optional[httpx.Client],
    timeout: float,
    refresh_token: Optional[str] = None,
) -> OAuthTokens:
    if http_client is not None:
        response = http_client.post(token_url, data=data, timeout=timeout)
    else:
        response = httpx.post(token_url, data=data, timeout=timeout)
    try:
        body: Any = response.json()
    except ValueError:
        body = {}
    if response.status_code != 200 or not body.get("access_token"):
        raise OAuthRefreshError(
            response.status_code,
            body.get("error") or "invalid_response",
            body.get("error_description"),
        )
    expires_in = body.get("expires_in")
    return OAuthTokens(
        access_token=body["access_token"],
        refresh_token=body.get("refresh_token") or refresh_token,
        expires_at=time.time() + expires_in if expires_in else None,
    )


@dataclass(frozen=True)
class AuthorizationRequest:
    url: str
    """Send the user's browser here to sign in and approve the app."""
    state: str
    """Compare with the ``state`` query param on the redirect before exchanging."""
    code_verifier: str
    """Keep server-side until the redirect; :func:`exchange_code` needs it."""


def authorization_url(
    client_id: str,
    redirect_uri: str,
    *,
    scopes: Optional[Iterable[str]] = None,
    state: Optional[str] = None,
    server_url: Optional[str] = None,
) -> AuthorizationRequest:
    """Start the authorization code + PKCE login for one user.

    ``redirect_uri`` must be registered on the OAuth application. ``scopes``
    defaults to every scope the application was registered with; SDK calls need
    ``api:read`` (and ``api:write`` to change anything).
    """
    code_verifier = secrets.token_urlsafe(64)
    challenge = (
        base64.urlsafe_b64encode(hashlib.sha256(code_verifier.encode()).digest())
        .rstrip(b"=")
        .decode()
    )
    state = state or secrets.token_urlsafe(24)
    params = {
        "response_type": "code",
        "client_id": client_id,
        "redirect_uri": redirect_uri,
        "code_challenge": challenge,
        "code_challenge_method": "S256",
        "state": state,
    }
    if scopes:
        params["scope"] = " ".join(scopes)
    return AuthorizationRequest(
        url=f"{_origin(server_url)}/oauth/authorize?{urlencode(params)}",
        state=state,
        code_verifier=code_verifier,
    )


def exchange_code(
    code: str,
    *,
    client_id: str,
    client_secret: str,
    redirect_uri: str,
    code_verifier: str,
    server_url: Optional[str] = None,
    token_url: Optional[str] = None,
    http_client: Optional[httpx.Client] = None,
    timeout: float = 30.0,
) -> OAuthTokens:
    """Exchange the ``code`` from the redirect for the user's token pair."""
    return _post_token(
        token_url or _token_url(server_url),
        {
            "grant_type": "authorization_code",
            "code": code,
            "client_id": client_id,
            "client_secret": client_secret,
            "redirect_uri": redirect_uri,
            "code_verifier": code_verifier,
        },
        http_client,
        timeout,
    )


class TokenManager:
    """Holds an OAuth token pair and refreshes it against ``/oauth/token``.

    Thread-safe. Refreshes are serialized on one lock so concurrent callers
    never replay a refresh token another caller already rotated.
    """

    def __init__(
        self,
        access_token: str,
        refresh_token: Optional[str] = None,
        *,
        client_id: Optional[str] = None,
        client_secret: Optional[str] = None,
        expires_in: Optional[float] = None,
        expires_at: Optional[float] = None,
        on_tokens: Optional[Callable[[OAuthTokens], None]] = None,
        server_url: Optional[str] = None,
        token_url: Optional[str] = None,
        timeout: float = 30.0,
        http_client: Optional[httpx.Client] = None,
    ) -> None:
        if refresh_token and not client_id:
            raise ValueError("client_id is required to refresh tokens")
        if expires_at is None and expires_in is not None:
            expires_at = time.time() + expires_in
        self._tokens = OAuthTokens(access_token, refresh_token, expires_at)
        self._client_id = client_id
        self._client_secret = client_secret
        self._on_tokens = on_tokens
        self._token_url = token_url or _token_url(server_url)
        self._timeout = timeout
        self._http = http_client
        self._lock = threading.Lock()

    @property
    def tokens(self) -> OAuthTokens:
        return self._tokens

    def access_token(self, stale: Optional[str] = None) -> str:
        """A usable access token, refreshing first when the current one is near
        expiry or equals ``stale`` (a token the server just rejected)."""
        if self._usable(stale):
            return self._tokens.access_token
        with self._lock:
            # Another caller may have refreshed while this one waited.
            if self._usable(stale):
                return self._tokens.access_token
            if not self._tokens.refresh_token:
                return self._tokens.access_token
            self._tokens = self._refresh(self._tokens.refresh_token)
            if self._on_tokens is not None:
                self._on_tokens(self._tokens)
            return self._tokens.access_token

    async def access_token_async(self, stale: Optional[str] = None) -> str:
        if self._usable(stale):
            return self._tokens.access_token
        return await asyncio.to_thread(self.access_token, stale)

    def _usable(self, stale: Optional[str]) -> bool:
        tokens = self._tokens
        if stale is not None and tokens.access_token == stale:
            return False
        return (
            tokens.expires_at is None
            or time.time() < tokens.expires_at - _REFRESH_MARGIN_SECONDS
        )

    def _refresh(self, refresh_token: str) -> OAuthTokens:
        data = {
            "grant_type": "refresh_token",
            "refresh_token": refresh_token,
            "client_id": self._client_id or "",
        }
        if self._client_secret:
            data["client_secret"] = self._client_secret
        return _post_token(self._token_url, data, self._http, self._timeout, refresh_token)


class TokenAuth(httpx.Auth):
    """``httpx.Auth`` that sends the manager's access token as a Bearer token
    and retries once with a refreshed token on a 401."""

    requires_request_body = True

    def __init__(self, manager: TokenManager) -> None:
        self.manager = manager

    def sync_auth_flow(self, request: httpx.Request):
        token = self.manager.access_token()
        _authorize(request, token)
        response = yield request
        if response.status_code == 401 and self.manager.tokens.refresh_token:
            _authorize(request, self.manager.access_token(stale=token))
            yield request

    async def async_auth_flow(self, request: httpx.Request):
        token = await self.manager.access_token_async()
        _authorize(request, token)
        response = yield request
        if response.status_code == 401 and self.manager.tokens.refresh_token:
            _authorize(request, await self.manager.access_token_async(stale=token))
            yield request


def _authorize(request: httpx.Request, token: str) -> None:
    # The server prefers tql_api_key over a Bearer token, and the SDK fills it
    # from TEXTQL_API_KEY whenever that is set.
    request.headers.pop("tql_api_key", None)
    request.headers["Authorization"] = f"Bearer {token}"


def token_manager_of(sdk: Textql) -> Optional[TokenManager]:
    auth = getattr(sdk.sdk_configuration.client, "auth", None)
    return auth.manager if isinstance(auth, TokenAuth) else None


def from_tokens(
    access_token: Optional[str] = None,
    refresh_token: Optional[str] = None,
    *,
    client_id: Optional[str] = None,
    client_secret: Optional[str] = None,
    expires_in: Optional[float] = None,
    expires_at: Optional[float] = None,
    on_tokens: Optional[Callable[[OAuthTokens], None]] = None,
    token_url: Optional[str] = None,
    manager: Optional[TokenManager] = None,
    server_url: Optional[str] = None,
    **kwargs: Any,
) -> Textql:
    """Build a :class:`~textql_sdk.Textql` authenticated with an OAuth token
    pair instead of an API key. Remaining keyword arguments go to ``Textql``.

    Pass ``manager`` to share one token pair across several SDK instances.
    """
    if "client" in kwargs or "async_client" in kwargs or "api_key" in kwargs:
        raise ValueError(
            "from_tokens builds its own clients and ignores api_key; "
            "pass auth=TokenAuth(manager) to your own httpx clients instead"
        )
    if manager is None:
        if not access_token:
            raise ValueError("pass access_token or manager")
        manager = TokenManager(
            access_token,
            refresh_token,
            client_id=client_id,
            client_secret=client_secret,
            expires_in=expires_in,
            expires_at=expires_at,
            on_tokens=on_tokens,
            server_url=server_url,
            token_url=token_url,
        )
    auth = TokenAuth(manager)
    return Textql(
        server_url=server_url,
        client=httpx.Client(follow_redirects=True, auth=auth),
        async_client=httpx.AsyncClient(follow_redirects=True, auth=auth),
        **kwargs,
    )


